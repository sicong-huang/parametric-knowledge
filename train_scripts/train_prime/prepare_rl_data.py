#!/usr/bin/env python3
"""Build the 4 nested RL task sets from the training questions the SFT model did NOT see.

The pool is every qa/train question minus the SFT config's questions (default: c4_43pct,
the RL starting checkpoint) — 16,725 questions. Configs are fractions of that pool, nested
and (hop, pattern)-stratified with the same rule as the SFT split (prepare_data.py):
    r1_10pct   10%
    r2_19pct   r1 + 10% of the remaining 90%           = 19.0%
    r3_43pct   r2 + 30% of the remaining 81%           = 43.3%
    r4_full    100% of the pool

Each question is used in BOTH modes: the overlay defines two train sources over the same
tasks file — `direct` (enable_thinking=false) and `reasoning` (enable_thinking=true) at
ratio 1:1. So prompts/epoch = 2 x questions and
    max_steps = ceil(epochs * 2 * questions / prompts_per_step),
    prompts_per_step = orchestrator.batch_size / orchestrator.train.group_size  (rl_base.toml).

Writes, per config:
    <out-dir>/<cfg>/tasks.jsonl     one row per question: qaid, question, answer, n_hop, pattern
    <out-dir>/<cfg>/qaids.txt
    <out-dir>/manifest.json         counts per hop and per (hop, pattern), steps
    <configs-dir>/<cfg>.toml        overlay: max_steps, run.name, the two train sources

    python3 train_scripts/train_prime/prepare_rl_data.py          # no GPU / prime-rl env needed
"""

import argparse
import json
import math
import random
import tomllib
from collections import Counter, defaultdict
from pathlib import Path

from prepare_data import HOPS, cumulative_fractions, load_qa

HERE = Path(__file__).resolve().parent
# Same fractions as SFT (10 / 19 / 43.3 / 100%), renamed for RL.
RL_NAMES = {"c2_10pct": "r1_10pct", "c3_19pct": "r2_19pct", "c4_43pct": "r3_43pct", "c1_full": "r4_full"}


def sample_pool(data, exclude: set[str], seed: int) -> dict[str, set[str]]:
    """Nested, (hop, pattern)-stratified subsets of the questions not in `exclude`."""
    strata = defaultdict(list)
    for hop in HOPS:
        for qaid, rec in data[(hop, "direct")].items():
            if qaid not in exclude:
                strata[(hop, rec["pattern"])].append(qaid)
    rng = random.Random(seed)
    selected = {RL_NAMES[c]: set() for c in cumulative_fractions()}
    for key in sorted(strata):
        ids = sorted(strata[key])
        rng.shuffle(ids)
        for cfg, frac in cumulative_fractions().items():
            selected[RL_NAMES[cfg]].update(ids[: round(frac * len(ids))])
    return selected, {f"{h}/{p}": len(v) for (h, p), v in strata.items()}


def write_overlay(path: Path, cfg: str, tasks: Path, n_q: int, frac: float, max_steps: int, run_prefix: str):
    src = (
        '[[orchestrator.train.source]]\nname = "{name}"\nenv.taskset.id = "kg_qa"\n'
        f'env.taskset.data_path = "{tasks}"\n'
        'env.agent.harness.id = "null"\nenv.agent.runtime.type = "subprocess"\n'
        "env.agent.sampling.chat_template_kwargs = {{ enable_thinking = {et} }}\n"
    )
    path.write_text(
        "# GENERATED by prepare_rl_data.py — do not edit by hand; rerun it instead.\n"
        f"# {cfg}: {frac:.1%} of the held-out pool -> {n_q} questions x 2 modes = {2 * n_q} prompts,\n"
        f"# {max_steps} steps. Both sources read the same tasks; they differ only in enable_thinking.\n"
        f"max_steps = {max_steps}\n\n"
        f'[run]\nname = "{run_prefix}-{cfg}"\n\n'
        + src.format(name="direct", et="false") + "\n"
        + src.format(name="reasoning", et="true")
    )


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--qa-dir", type=Path, default=Path("qa/train"))
    p.add_argument("--exclude-qaids", type=Path, default=Path("data/sft_prime/c4_43pct/qaids.txt"),
                   help="questions the starting SFT model was trained on")
    p.add_argument("--out-dir", type=Path, default=Path("data/rl_prime"))
    p.add_argument("--configs-dir", type=Path, default=HERE / "configs" / "rl")
    p.add_argument("--base-config", type=Path, default=HERE / "configs" / "rl" / "base.toml")
    p.add_argument("--epochs", type=float, default=1.0)
    p.add_argument("--seed", type=int, default=100)
    p.add_argument("--run-prefix", default="qwen3.5-0.8b-c4", help="run.name = <prefix>-<cfg>")
    args = p.parse_args()

    base = tomllib.loads(args.base_config.read_text())
    batch, group = base["orchestrator"]["batch_size"], base["orchestrator"]["train"]["group_size"]
    assert batch % group == 0, "batch_size must be divisible by group_size"
    prompts_per_step = batch // group

    data = load_qa(args.qa_dir)
    exclude = set(args.exclude_qaids.read_text().split())
    selected, pool_by_pattern = sample_pool(data, exclude, args.seed)
    pool = sum(pool_by_pattern.values())
    print(f"pool: {pool} questions ({len(exclude)} excluded from {args.exclude_qaids})")

    recs = {qaid: (hop, rec) for hop in HOPS for qaid, rec in data[(hop, "direct")].items()}
    manifest = {"qa_dir": str(args.qa_dir), "exclude_qaids": str(args.exclude_qaids), "excluded": len(exclude),
                "pool_questions": pool, "seed": args.seed, "epochs": args.epochs,
                "prompts_per_step": prompts_per_step, "group_size": group, "configs": {}}
    args.configs_dir.mkdir(parents=True, exist_ok=True)
    for sft_cfg, frac in cumulative_fractions().items():
        cfg = RL_NAMES[sft_cfg]
        ids = sorted(selected[cfg])
        assert not (set(ids) & exclude)
        rows = []
        for qaid in ids:
            hop, rec = recs[qaid]
            rows.append({"qaid": qaid, "question": rec["question"], "answer": rec["answer"],
                         "n_hop": hop, "pattern": rec["pattern"]})
        random.Random(args.seed).shuffle(rows)
        out = args.out_dir / cfg
        out.mkdir(parents=True, exist_ok=True)
        with open(out / "tasks.jsonl", "w") as f:
            f.writelines(json.dumps(r) + "\n" for r in rows)
        (out / "qaids.txt").write_text("\n".join(ids) + "\n")

        max_steps = math.ceil(args.epochs * 2 * len(rows) / prompts_per_step)
        write_overlay(args.configs_dir / f"{cfg}.toml", cfg, (out / "tasks.jsonl").resolve(), len(rows), frac,
                      max_steps, args.run_prefix)
        pat = Counter(f"{r['n_hop']}/{r['pattern']}" for r in rows)
        manifest["configs"][cfg] = {
            "fraction_of_pool": round(frac, 4),
            "questions": len(rows),
            "prompts_per_epoch": 2 * len(rows),
            "questions_by_hop": dict(sorted(Counter(r["n_hop"] for r in rows).items())),
            "questions_by_hop_pattern": {k: {"questions": n, "available": pool_by_pattern[k],
                                             "fraction": round(n / pool_by_pattern[k], 4)}
                                         for k, n in sorted(pat.items())},
            "max_steps": max_steps,
        }
        print(f"{cfg:9s} {frac:6.1%}  questions={len(rows):6d}  prompts={2 * len(rows):6d}  max_steps={max_steps:4d}  "
              f"{manifest['configs'][cfg]['questions_by_hop']}")

    chain = ["r1_10pct", "r2_19pct", "r3_43pct", "r4_full"]
    assert all(selected[a] <= selected[b] for a, b in zip(chain, chain[1:])), "subsets are not nested"
    (args.out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2))
    print(f"Wrote {args.out_dir}/manifest.json and overlays in {args.configs_dir}")


if __name__ == "__main__":
    main()
