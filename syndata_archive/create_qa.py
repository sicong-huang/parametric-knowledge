def _get_person_ids_from_edges(edges: list[dict]) -> list[str]:
    """Return deduplicated person entity IDs found across edges, in order."""
    person_ids: list[str] = []
    seen: set[str] = set()
    for edge in edges:
        for id_key, type_key in [("source_id", "source_type"), ("target_id", "target_type")]:
            eid = edge[id_key]
            if _is_person(edge[type_key]) and eid not in seen:
                person_ids.append(eid)
                seen.add(eid)
    return person_ids


# -- sentence style (LLM) for 2-hop --

_2HOP_SENTENCE_1P_INSTRUCTION = (
    "You write a single complete sentence that answers a question about a person. "
    "Use the provided biography as context. The sentence should read naturally, "
    "as if extracted from a Wikipedia article. It must contain the answer entity. "
    "Output ONLY the sentence — no preamble, no extras."
)


def _build_2hop_sentence_1p_prompt(
    question: str, answer: str, biography: str,
) -> str:
    return (
        f"Biography:\n{biography}\n\n"
        f"Question: {question}\n"
        f"Answer: {answer}\n\n"
        f"Write a single complete sentence that answers the question, "
        f"using the biography as stylistic reference."
    )


_2HOP_SENTENCE_2P_INSTRUCTION = (
    "You write a single complete sentence that answers a two-hop question "
    "involving two people. Use the provided biographies as context. "
    "The sentence should read naturally, as if extracted from an encyclopedia, "
    "and should resemble a one-step reasoning chain that connects the two people "
    "to arrive at the answer. It must contain the answer entity. "
    "Output ONLY the sentence — no preamble, no extras."
)


def _build_2hop_sentence_2p_prompt(
    question: str, answer: str, bio_1: str, name_1: str, bio_2: str, name_2: str,
) -> str:
    return (
        f"Biography of {name_1}:\n{bio_1}\n\n"
        f"Biography of {name_2}:\n{bio_2}\n\n"
        f"Question: {question}\n"
        f"Answer: {answer}\n\n"
        f"Write a single complete sentence that answers the question. "
        f"The sentence should resemble a one-step reasoning connecting "
        f"information about both people to arrive at the answer."
    )


def _generate_2hop_sentence_answer(
    client: OpenAI, model: str, record: dict,
    bio_map: dict[str, str], id_to_name: dict[str, str],
) -> dict:
    person_ids = _get_person_ids_from_edges(record["edges"])

    if len(person_ids) == 1:
        biography = bio_map.get(person_ids[0], "")
        prompt = _build_2hop_sentence_1p_prompt(
            record["question"], record["answer"], biography,
        )
        instruction = _2HOP_SENTENCE_1P_INSTRUCTION
    else:
        bio_1 = bio_map.get(person_ids[0], "")
        bio_2 = bio_map.get(person_ids[1], "")
        name_1 = id_to_name.get(person_ids[0], person_ids[0])
        name_2 = id_to_name.get(person_ids[1], person_ids[1])
        prompt = _build_2hop_sentence_2p_prompt(
            record["question"], record["answer"],
            bio_1, name_1, bio_2, name_2,
        )
        instruction = _2HOP_SENTENCE_2P_INSTRUCTION

    response = client.responses.parse(
        model=model,
        instructions=instruction,
        input=prompt,
        text_format=SentenceAnswer,
    )
    return {
        "qaid": record["qaid"],
        "question": record["question"],
        "full_answer": response.output_parsed.full_answer,
        "answer": record["answer"],
    }


