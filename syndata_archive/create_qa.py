def _generate_2hop_reasoning_answer(
    client: OpenAI, model: str, record: dict,
    bio_map: dict[str, str], id_to_name: dict[str, str],
) -> dict:
    person_ids = _get_person_ids_from_edges(record["edges"])

    if record.get("pattern") == "P,P->NP" and len(person_ids) >= 2:
        bio_1 = bio_map.get(person_ids[0], "")
        bio_2 = bio_map.get(person_ids[1], "")
        name_1 = id_to_name.get(person_ids[0], person_ids[0])
        name_2 = id_to_name.get(person_ids[1], person_ids[1])
        prompt = _build_2hop_reasoning_join_prompt(
            record["question"], record["answer"],
            bio_1, name_1, bio_2, name_2,
        )
        instruction = _2HOP_REASONING_JOIN_INSTRUCTION
    elif len(person_ids) == 1:
        biography = bio_map.get(person_ids[0], "")
        prompt = _build_2hop_reasoning_1p_prompt(
            record["question"], record["answer"], biography,
        )
        instruction = _2HOP_REASONING_1P_INSTRUCTION
    else:
        bio_1 = bio_map.get(person_ids[0], "")
        bio_2 = bio_map.get(person_ids[1], "")
        name_1 = id_to_name.get(person_ids[0], person_ids[0])
        name_2 = id_to_name.get(person_ids[1], person_ids[1])
        prompt = _build_2hop_reasoning_2p_prompt(
            record["question"], record["answer"],
            bio_1, name_1, bio_2, name_2,
        )
        instruction = _2HOP_REASONING_2P_INSTRUCTION

    response = client.responses.parse(
        model=model,
        instructions=instruction,
        input=prompt,
        text_format=ReasoningAnswer,
    )
    parsed = response.output_parsed
    full_answer = f"<think>\n{parsed.thinking}\n</think>\n{parsed.answer}"
    return {
        "qaid": record["qaid"],
        "question": record["question"],
        "full_answer": full_answer,
        "answer": record["answer"],
    }


