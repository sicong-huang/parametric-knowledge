"""
Create QA datasets from a knowledge graph run directory.

Subcommands
-----------

1_hop
    Generate 1-hop question-answer pairs from edges.jsonl. Edges are grouped
    by (source_id, relation_type) and only groups with a unique answer (one
    target) are kept. Questions are generated by an LLM; answers come directly
    from the graph. Output: stratified_1hop/qa_1_hop.jsonl

    Usage:
        uv run create_qa.py 1_hop --dir data/bio/run5 --sample 20000 --max-workers 100

1_hop_full_answer
    Read the generated stratified_1hop/qa_1_hop.jsonl and produce styled full-answer files.
    Three styles are available:

      direct    -- full_answer = answer (no LLM call)
      sentence  -- full_answer is one complete sentence derived from the
                   person's wiki biography (LLM call)
      reasoning -- full_answer wraps a thinking blurb in <think>...</think>
                   tags followed by the direct answer (LLM call)

    Usage:
        uv run create_qa.py 1_hop_full_answer --dir data/bio/run5 --style direct
        uv run create_qa.py 1_hop_full_answer --dir data/bio/run5 --style sentence --max-workers 100
        uv run create_qa.py 1_hop_full_answer --dir data/bio/run5 --style reasoning --max-workers 100

    Output files are written to stratified_1hop/ in the run directory:
        stratified_1hop/qa_1_hop_direct.jsonl
        stratified_1hop/qa_1_hop_sentence.jsonl
        stratified_1hop/qa_1_hop_reasoning.jsonl

2_hop
    Generate 2-hop question-answer pairs from edges.jsonl. Two-hop paths are
    enumerated across three patterns that share a common connector node:

      P,P->NP    -- two persons point to the same non-person (join; answer = NP)
      NP<-P->NP  -- one person points to two non-persons
      P->P->NP   -- person A relates to person B who relates to a non-person

    Only paths with a unique answer (enforced per relation type) are kept.
    Questions are generated by an LLM; answers come directly from the graph.
    Output: qa/qa_2_hop.jsonl

    Usage:
        uv run create_qa.py 2_hop --dir data/bio/run5 --sample 20000 --max-workers 100

2_hop_full_answer
    Read the generated qa/qa_2_hop.jsonl and produce styled full-answer files.

      direct    -- full_answer = answer (no LLM call)
      sentence  -- full_answer is one complete sentence derived from the
                   involved person(s)' biography (LLM call); for one-person
                   paths a single biography is given, for two-person paths
                   both biographies are given and the sentence resembles a
                   one-step reasoning to the answer
      reasoning -- full_answer wraps a thinking blurb in <think>...</think>
                   tags followed by the direct answer (LLM call); for
                   one-person paths recalls facts about that person, for
                   two-person paths chains facts about both people

    Usage:
        uv run create_qa.py 2_hop_full_answer --dir data/bio/run5 --style direct
        uv run create_qa.py 2_hop_full_answer --dir data/bio/run5 --style sentence --max-workers 100
        uv run create_qa.py 2_hop_full_answer --dir data/bio/run5 --style reasoning --max-workers 100

    Output files are written to qa/ in the run directory:
        qa/qa_2_hop_direct.jsonl
        qa/qa_2_hop_sentence.jsonl
        qa/qa_2_hop_reasoning.jsonl

Common options
--------------
    --qa-base-url   OpenAI API base URL (default: $QA_BASE_URL or $BIO_BASE_URL)
    --qa-api-key    API key (default: $QA_API_KEY or $BIO_API_KEY)
    --model         Model id (default: gemma4)
    --max-workers   Parallel LLM workers (default: 8)
    --short         Only process the first 200 records (for dev/testing)
"""

